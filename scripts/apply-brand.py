#!/usr/bin/env python3
"""Apply the brand kit to the Open Practice site and give every page a real social card.

The repo ships a mark, a palette, a favicon and no social meta at all, and it links
`/activity-library-hero.webp` from a hard-coded path. This script:

  1. copies the kit into `apps/web/public/brand/` under names the site can serve for years
  2. writes a `brand/head.html` partial — icons + Open Graph + Twitter card — and injects it into
     every top-level HTML page that does not already carry `<meta property="og:image"`
  3. rewrites `index.html`'s hero reference to the version that actually exists

Idempotent: running it twice changes nothing. Run from the repo root.
"""
import os
import re
import shutil
import sys

KIT = os.environ.get("OP_KIT", os.path.expanduser("~/open-practice-brand"))
PUB = "apps/web/public"
BRAND = os.path.join(PUB, "brand")
SITE = "https://open-practice.zlnew.workers.dev"

COPIES = {
    "icons/favicon-32.png": "brand/favicon-32.png",
    "icons/apple-touch-icon.png": "brand/apple-touch-icon.png",
    "icons/icon-192.png": "brand/icon-192.png",
    "icons/icon-512.png": "brand/icon-512.png",
    "banners/og-1200x630.png": "brand/og-1200x630.png",
    "banners/x-header-1500x500.png": "brand/x-header-1500x500.png",
    "banners/github-social-1280x640.png": "brand/github-social-1280x640.png",
    "pins/pin-1-activities.png": "brand/card-activities.png",
    "pins/pin-2-library.png": "brand/card-library.png",
    "pins/pin-3-promise.png": "brand/card-promise.png",
    "posts/square-1.png": "brand/quote-1.png",
    "posts/square-2.png": "brand/quote-2.png",
    "stories/story-1.png": "brand/story-1.png",
    "stories/story-2.png": "brand/story-2.png",
}

HEAD = """<!-- social + icons: generated by scripts/apply-brand.py, safe to leave alone -->
<link rel="apple-touch-icon" sizes="180x180" href="/brand/apple-touch-icon.png">
<link rel="icon" type="image/png" sizes="32x32" href="/brand/favicon-32.png">
<link rel="icon" type="image/png" sizes="192x192" href="/brand/icon-192.png">
<link rel="manifest" href="/brand/site.webmanifest">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Open Practice">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{desc}">
<meta property="og:image" content="{site}/brand/og-1200x630.png">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="Open Practice — practical AI learning, free and without signup">
<meta property="og:url" content="{url}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{title}">
<meta name="twitter:description" content="{desc}">
<meta name="twitter:image" content="{site}/brand/og-1200x630.png">
<meta name="theme-color" content="#FDF7EE">
"""

MANIFEST = """{
  "name": "Open Practice — Practical AI Learning",
  "short_name": "Open Practice",
  "description": "Free, practical AI learning. Build something real and keep what you make.",
  "start_url": "/",
  "display": "browser",
  "background_color": "#FDF7EE",
  "theme_color": "#FDF7EE",
  "icons": [
    { "src": "/brand/icon-192.png", "sizes": "192x192", "type": "image/png" },
    { "src": "/brand/icon-512.png", "sizes": "512x512", "type": "image/png" },
    { "src": "/brand/apple-touch-icon.png", "sizes": "180x180", "type": "image/png" }
  ]
}
"""

# pages whose own subject sets the card; everything else gets the house card
PER_PAGE = {
    "activities.html": ("86 free AI activities you can actually finish",
                        "Guided experiments with worked examples, evidence checklists and offline files."),
    "curriculum.html": ("The Open Practice curriculum map",
                        "Six build paths, 86 activities, and the order they make sense in."),
    "library.html": ("The free AI practice library",
                     "Handbooks, practice packs and offline HTML workspaces. No account needed to read."),
}
DEFAULT = ("Open Practice — free practical AI learning",
           "Pick a build path, make something real, and keep the evidence. Free, no signup.")


def title_of(html: str) -> str:
    m = re.search(r"<title[^>]*>(.*?)</title>", html, re.S | re.I)
    return re.sub(r"\s+", " ", m.group(1)).strip() if m else "Open Practice"


def main() -> int:
    if not os.path.isdir(PUB):
        sys.exit("run me from the open-practice repo root (apps/web/public not found)")
    os.makedirs(BRAND, exist_ok=True)

    for src, dst in COPIES.items():
        s = os.path.join(KIT, src)
        if not os.path.exists(s):
            sys.exit(f"missing kit file: {s}")
        shutil.copy2(s, os.path.join(PUB, dst))
    with open(os.path.join(BRAND, "site.webmanifest"), "w") as fh:
        fh.write(MANIFEST)
    print(f"copied {len(COPIES)} assets + manifest into {BRAND}")

    pages = sorted(p for p in os.listdir(PUB) if p.endswith(".html"))
    touched = skipped = 0
    for page in pages:
        path = os.path.join(PUB, page)
        html = open(path, encoding="utf-8").read()
        if 'property="og:image"' in html or "property='og:image'" in html:
            skipped += 1
            continue
        if "</head>" not in html:
            skipped += 1
            continue
        title, desc = PER_PAGE.get(page, DEFAULT)
        url = f"{SITE}/" if page == "index.html" else f"{SITE}/{page}"
        block = HEAD.format(title=title, desc=desc, site=SITE, url=url)
        html = html.replace("</head>", block + "</head>", 1)
        open(path, "w", encoding="utf-8").write(html)
        touched += 1

    # the hero image the homepage asks for does not exist under that name; point it at the real one
    idx = os.path.join(PUB, "index.html")
    h = open(idx, encoding="utf-8").read()
    fixed = h.replace('/brand/activity-library-hero.webp', '/brand/activity-library-hero.png')
    if fixed != h:
        open(idx, "w", encoding="utf-8").write(fixed)
        if not os.path.exists(os.path.join(PUB, "brand", "activity-library-hero.png")):
            shutil.copy2(os.path.join("branding", "activity-library-hero.png"),
                         os.path.join(PUB, "brand", "activity-library-hero.png"))
        print("index.html: hero image now points at the PNG that exists")

    print(f"head injected into {touched} pages, {skipped} already had cards or no </head>")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
